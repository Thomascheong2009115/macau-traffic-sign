from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description="Single-model compatibility entrypoint for Kaggle.")
    parser.add_argument("--checkpoint", default=None)
    parser.add_argument("--main_checkpoint", default=None)
    parser.add_argument("--base_checkpoint", default=None)
    parser.add_argument("--expert_checkpoint", default=None)
    parser.add_argument("--input_csv", required=True)
    parser.add_argument("--image_dir", required=True)
    parser.add_argument("--output", "--output_csv", dest="output_csv", required=True)
    parser.add_argument("--debug_csv", required=True)
    parser.add_argument("--missing_csv", default=None)
    parser.add_argument("--classes", default=str(PROJECT_ROOT / "classes.txt"))
    parser.add_argument("--device", default="auto")
    args = parser.parse_args()

    checkpoint = args.checkpoint or args.main_checkpoint or str(PROJECT_ROOT / "checkpoints" / "final_single_resnet50.pt")
    output_csv = Path(args.output_csv)
    debug_csv = Path(args.debug_csv)
    working_dir = output_csv.parent
    working_dir.mkdir(parents=True, exist_ok=True)
    debug_crop_dir = working_dir / "debug_crops"
    debug_crop_dir.mkdir(parents=True, exist_ok=True)

    config_path = working_dir / "single_model_exam_config.json"
    config = {
        "mode": "single",
        "checkpoint": str(Path(checkpoint)),
        "model_name": "resnet50",
        "image_size": 256,
        "pad_to_square": 1,
        "preprocessing_profile": "clean_pad",
        "bbox_expansion_ratio": 0.08,
        "use_tta": False,
        "note": "Kaggle single-model compatibility config generated by src/ensemble_infer.py",
    }
    config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")

    device = args.device
    if device == "auto":
        device = "cuda"

    infer_script = (
        PROJECT_ROOT
        / "experiments"
        / "final_bbox_crop_rebuild"
        / "long_horizon_97plus"
        / "deployment"
        / "infer_exam_long_horizon.py"
    )
    cmd = [
        sys.executable,
        str(infer_script),
        "--input_csv",
        str(args.input_csv),
        "--image_dir",
        str(args.image_dir),
        "--output_csv",
        str(output_csv),
        "--debug_csv",
        str(debug_csv),
        "--debug_crop_dir",
        str(debug_crop_dir),
        "--config",
        str(config_path),
        "--classes",
        str(args.classes),
        "--device",
        device,
    ]
    subprocess.run(cmd, cwd=str(PROJECT_ROOT), check=True)

    if args.missing_csv:
        Path(args.missing_csv).write_text("img\n", encoding="utf-8")


if __name__ == "__main__":
    main()
